/**
 * Downloads the editorial photos listed in data/photos.json (all under the
 * Unsplash License) and writes responsive AVIF + WebP variants to
 * public/img/photos. Also regenerates CREDITS.md from the same manifest.
 *
 * Usage: npm run images            (skips files that already exist)
 *        npm run images -- --force (rebuilds everything)
 */
const fs = require('fs/promises');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'public', 'img', 'photos');
const photos = require('../data/photos.json');

const WIDTHS = [640, 1280, 1920];
const SOURCE_WIDTH = 2400;
const FORMATS = {
  avif: (img) => img.avif({ quality: 50, effort: 4 }),
  webp: (img) => img.webp({ quality: 72 }),
};
const force = process.argv.includes('--force');

async function exists(file) {
  try {
    await fs.access(file);
    return true;
  } catch {
    return false;
  }
}

async function download(unsplashId) {
  const url = `https://images.unsplash.com/photo-${unsplashId}?w=${SOURCE_WIDTH}&q=90&fm=jpg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed (${res.status}) for ${unsplashId}`);
  return Buffer.from(await res.arrayBuffer());
}

async function buildPhoto(photo) {
  const targets = WIDTHS.flatMap((w) =>
    Object.keys(FORMATS).map((fmt) => ({ w, fmt, file: path.join(OUT_DIR, `${photo.key}-${w}.${fmt}`) })),
  );
  if (!force && (await Promise.all(targets.map((t) => exists(t.file)))).every(Boolean)) {
    console.log(`skip  ${photo.key}`);
    return;
  }

  let source = await download(photo.unsplashId);
  // Optional crop (fractions of the source) to remove distracting edges such as signage.
  if (photo.crop) {
    const meta = await sharp(source).metadata();
    source = await sharp(source)
      .extract({
        left: Math.round(photo.crop.left * meta.width),
        top: Math.round(photo.crop.top * meta.height),
        width: Math.round(photo.crop.width * meta.width),
        height: Math.round(photo.crop.height * meta.height),
      })
      .toBuffer();
  }
  const { width: sourceWidth } = await sharp(source).metadata();
  for (const { w, fmt, file } of targets) {
    // Never upscale: small sources keep their native width.
    const img = sharp(source).resize({ width: Math.min(w, sourceWidth) });
    await FORMATS[fmt](img).toFile(file);
  }
  console.log(`built ${photo.key}`);
}

function creditsMarkdown() {
  const rows = photos
    .map(
      (p) =>
        `| \`${p.key}\` | [${p.photographer}](${p.profileUrl}) | [Unsplash](${p.pageUrl}) | Unsplash License |`,
    )
    .join('\n');
  return `# Credits

All editorial photography is used under the [Unsplash License](https://unsplash.com/license):
free to use for commercial and non-commercial purposes, no permission needed.
Attribution is not required but is given here. No photo shows a real brand's logo or text.

Product images are original SVG illustrations generated in \`public/js/placeholder.js\`.
The brand name and all copy are fictional.

This file is generated by \`npm run images\` from \`data/photos.json\`.

| Image key | Photographer | Source | License |
| --- | --- | --- | --- |
${rows}
`;
}

/**
 * Writes the browser-side manifest: widths, intrinsic size (to prevent layout
 * shift), focal point and localised alt text for every photo.
 */
async function writeBrowserManifest() {
  const entries = {};
  for (const p of photos) {
    const meta = await sharp(path.join(OUT_DIR, `${p.key}-${WIDTHS[1]}.webp`)).metadata();
    entries[p.key] = { width: meta.width, height: meta.height, focus: p.focus, alt: p.alt };
  }
  const source = `// Generated by scripts/build-images.js from data/photos.json. Do not edit by hand.
export const PHOTO_WIDTHS = ${JSON.stringify(WIDTHS)};
export const PHOTOS = ${JSON.stringify(entries, null, 2)};
`;
  await fs.writeFile(path.join(ROOT, 'public', 'js', 'photos.js'), source);
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });
  for (const photo of photos) await buildPhoto(photo);
  await writeBrowserManifest();
  await fs.writeFile(path.join(ROOT, 'CREDITS.md'), creditsMarkdown());
  console.log('public/js/photos.js and CREDITS.md updated');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
